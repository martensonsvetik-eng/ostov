// Regenerates src/components/sections/logo-paths.ts: the ОСТОВ / OSTOV wordmark
// (Cormorant Garamond 600, 28 px, tracking 0.12em) converted to SVG paths.
// Usage: node scripts/gen-logo-paths.mjs
import opentype from 'opentype.js';
import fs from 'node:fs';

const dir = 'node_modules/@fontsource/cormorant-garamond/files/';
const size = 28;
const track = 0.12 * size;
const n = (v) => {
  if (!Number.isFinite(v)) throw new Error('non-finite coordinate in glyph path');
  return String(+v.toFixed(2));
};

function wordmark(file, text) {
  const b = fs.readFileSync(dir + file);
  const font = opentype.parse(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength));
  let x = 0;
  let d = '';
  for (const ch of text) {
    const g = font.charToGlyph(ch);
    if (g.index === 0) throw new Error(`missing glyph ${ch}`);
    for (const c of g.getPath(x, size * 0.7, size).commands) {
      if (c.type === 'Z') d += 'Z';
      else if (c.type === 'M' || c.type === 'L') d += `${c.type}${n(c.x)} ${n(c.y)}`;
      else if (c.type === 'Q') d += `Q${n(c.x1)} ${n(c.y1)} ${n(c.x)} ${n(c.y)}`;
      else if (c.type === 'C') d += `C${n(c.x1)} ${n(c.y1)} ${n(c.x2)} ${n(c.y2)} ${n(c.x)} ${n(c.y)}`;
    }
    x += (g.advanceWidth * size) / font.unitsPerEm + track;
  }
  return { d, w: +(x - track).toFixed(1) };
}

const out = {
  ru: wordmark('cormorant-garamond-cyrillic-600-normal.woff', 'ОСТОВ'),
  en: wordmark('cormorant-garamond-latin-600-normal.woff', 'OSTOV'),
};
fs.writeFileSync(
  'src/components/sections/logo-paths.ts',
  '// Generated by scripts/gen-logo-paths.mjs: wordmark outlines, Cormorant Garamond 600, 28 px, tracking 0.12em (brief §11).\n' +
    `export const logoPaths = ${JSON.stringify(out)} as const;\n`,
);
console.log('ru w', out.ru.w, 'en w', out.en.w);
